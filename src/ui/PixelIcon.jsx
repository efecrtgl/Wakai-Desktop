const cache = new Map();
function rects(name) {
  if (!cache.has(name)) {
    const out = [];
    (ICONS[name] ?? []).forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] !== '#') {
          x++;
          continue;
        }
        let run = 1;
        while (row[x + run] === '#') run++;
        out.push({ x, y, w: run });
        x += run;
      }
    });
    cache.set(name, out);
  }
  return cache.get(name);
}

/** Ham piksel simge (temadan bağımsız). */
export const RawPixelIcon = memo(function RawPixelIcon({ name, size = 16 }) {
  return (
    <svg viewBox="0 0 12 12" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true" fill="currentColor">
      {rects(name).map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} />
      ))}
    </svg>
  );
});

/**
 * Temanın simge setine göre piksel ya da çizgi simge. (Ad geçmişten kalma: tüm uygulama bu
 * bileşeni kullanır.) Çizgi sette karşılığı olmayan simge piksel olarak çizilir.
 */
export function PixelIcon({ name, size = 16 }) {
  const theme = useActiveTheme();
  if (theme?.style.icons === 'line' && LINE_ICONS[name]) return <LineIcon name={name} size={size} />;
  return <RawPixelIcon name={name} size={size} />;
}

